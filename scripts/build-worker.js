#!/usr/bin/env node
'use strict';
// Generates worker/index.mjs: one self-contained file to paste into Cloudflare (no bundler needed).
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const i18n = JSON.parse(read('i18n/strings.json'));
const data = JSON.parse(read('data/messages.json'));
const contacts = JSON.parse(read('data/contacts.json'));
const wrap = (src) => '(() => { const module = { exports: {} }; ' + src + '\n return module.exports; })()';

function build() {
  return `// GENERATED by scripts/build-worker.js - do not edit. Source: lib.js, mcp/core.js, data/messages.json, data/contacts.json.
// Remote MCP (Streamable HTTP, JSON responses). Phone numbers of callers exist only in the request and the
// response and are never stored or logged. The only state is a global hourly issue counter (no personal data)
// in the optional RATE KV namespace, used by open_issue.
const WA = ${wrap(read('lib.js'))};
const createMcp = ${wrap(read('mcp/core.js'))};
const DATA = ${JSON.stringify(data)};
const CONTACTS = ${JSON.stringify(contacts)};
const LANGS = ${JSON.stringify(Object.keys(i18n.meta))};
const mcp = createMcp(WA, DATA, LANGS, CONTACTS);

const REPO = 'reihlinstinct/wa-link-generator';
const MAX_ISSUES_PER_HOUR = 5;
const eq = (a, b) => { if (a.length !== b.length) return false; let d = 0; for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i); return d === 0; };

// open_issue: bearer token, input checks, global hourly cap, GitHub token only in the Worker secret.
async function openIssue(req, env, args) {
  if (!env.MCP_ISSUE_TOKEN || !env.GH_ISSUES_TOKEN || !env.RATE) throw new Error('open_issue is not configured');
  const auth = req.headers.get('authorization') || '';
  if (!eq(auth, 'Bearer ' + env.MCP_ISSUE_TOKEN)) throw new Error('open_issue needs a valid bearer token');
  const issue = mcp.checkIssue(args);
  const key = 'issues:' + new Date().toISOString().slice(0, 13);
  const n = parseInt((await env.RATE.get(key)) || '0', 10);
  if (n >= MAX_ISSUES_PER_HOUR) throw new Error('rate limit reached, try again later');
  await env.RATE.put(key, String(n + 1), { expirationTtl: 7200 });
  const r = await fetch('https://api.github.com/repos/' + REPO + '/issues', {
    method: 'POST',
    headers: { authorization: 'Bearer ' + env.GH_ISSUES_TOKEN, accept: 'application/vnd.github+json', 'user-agent': 'wa-link-generator-mcp', 'content-type': 'application/json' },
    body: JSON.stringify({ title: issue.title, body: issue.body + '\\n\\n_Opened through the MCP endpoint._', labels: ['from-mcp'] })
  });
  if (!r.ok) throw new Error('GitHub refused the issue (' + r.status + ')');
  const j = await r.json();
  return { url: j.html_url, number: j.number, note: 'The issue is public.' };
}
async function handleMsg(req, env, m) {
  if (m && m.method === 'tools/call' && m.params && m.params.name === 'open_issue' && m.id !== undefined) {
    try {
      const out = await openIssue(req, env, m.params.arguments);
      return { jsonrpc: '2.0', id: m.id, result: { content: [{ type: 'text', text: JSON.stringify(out) }], structuredContent: out } };
    } catch (e) {
      return { jsonrpc: '2.0', id: m.id, result: { content: [{ type: 'text', text: String(e.message) }], isError: true } };
    }
  }
  return mcp.handle(m);
}

const CORS = {
  'access-control-allow-origin': '*',
  'access-control-allow-methods': 'POST, OPTIONS',
  'access-control-allow-headers': 'content-type, mcp-protocol-version, mcp-session-id, accept',
  'cache-control': 'no-store'
};
const json = (obj, status = 200) => new Response(JSON.stringify(obj), { status, headers: { ...CORS, 'content-type': 'application/json' } });

export default {
  async fetch(req, env) {
    env = env || {};
    const url = new URL(req.url);
    if (req.method === 'OPTIONS') return new Response(null, { status: 204, headers: CORS });
    if (url.pathname === '/mcp') {
      if (req.method !== 'POST') return new Response('POST JSON-RPC to /mcp', { status: 405, headers: { ...CORS, allow: 'POST, OPTIONS' } });
      const text = await req.text();
      if (text.length > 16384) return json({ jsonrpc: '2.0', id: null, error: { code: -32600, message: 'Request too large' } }, 413);
      let body;
      try { body = JSON.parse(text); } catch (e) { return json({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Parse error' } }, 400); }
      if (Array.isArray(body)) {
        if (body.length > 20) return json({ jsonrpc: '2.0', id: null, error: { code: -32600, message: 'Batch too large' } }, 400);
        const out = (await Promise.all(body.map((m) => handleMsg(req, env, m)))).filter(Boolean);
        return out.length ? json(out) : new Response(null, { status: 202, headers: CORS });
      }
      const out = await handleMsg(req, env, body);
      return out ? json(out) : new Response(null, { status: 202, headers: CORS });
    }
    if (url.pathname === '/' || url.pathname === '/health') {
      return new Response('wa-link-generator MCP endpoint: POST /mcp (JSON-RPC 2.0). Phone numbers are not stored or logged. Source: https://github.com/reihlinstinct/wa-link-generator\\n', { headers: { ...CORS, 'content-type': 'text/plain; charset=utf-8' } });
    }
    return new Response('Not found', { status: 404, headers: CORS });
  }
};
`;
}
if (require.main === module) fs.writeFileSync(path.join(root, 'worker/index.mjs'), build());
module.exports = { build };
